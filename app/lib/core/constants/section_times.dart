/// 扬大节次作息表（春夏 / 秋冬两套）。
///
/// 数据来源（2026-08）：
/// - 春夏季：全部 12 小节时间取自真实教务课表页面样本
///   （docs/samples/班级课表.html 表头「第N小节(HH:MM-HH:MM)」），可靠；
/// - 秋冬季：上午沿用官方已确认时间；下午 / 晚上按"45 分钟 + 10 分钟课间"
///   的同一规律前移半小时推得，⚠️ 待秋冬季样本核对。
///
/// 结构：12 小节，下标 0 = 第 1 小节。大节 = 相邻小节（1-2、3-4，最多 6-8 三节连排）。
/// 后续会做成学期级可配置（settings 表存 JSON），当前先内置常量。
class SectionTimes {
  SectionTimes._();

  static const int sectionCount = 12;

  /// 春夏季（大致 5 月 - 9 月）：✅ 真实样本提取，可靠
  static const List<(String, String)> springSummer = [
    ('08:00', '08:45'),
    ('08:55', '09:40'),
    ('09:55', '10:40'),
    ('10:50', '11:35'),
    ('11:45', '12:30'),
    ('14:30', '15:15'),
    ('15:25', '16:10'),
    ('16:20', '17:05'),
    ('17:15', '18:00'),
    ('18:10', '18:55'),
    ('19:30', '20:15'),
    ('20:25', '21:10'),
  ];

  /// 秋冬季（大致 10 月 - 次年 4 月）：上午与春夏一致；下午第 6 节 14:00
  /// 起（用户 2026-08-12 记忆确认，原推断 13:30 已修正）；晚上第 11 节 19:00
  /// 起（按下午同幅度前移推断，⚠️ 待开学后班级课表表头核对）
  static const List<(String, String)> autumnWinter = [
    ('08:00', '08:45'),
    ('08:55', '09:40'),
    ('09:55', '10:40'),
    ('10:50', '11:35'),
    ('11:45', '12:30'),
    ('14:00', '14:45'),
    ('14:55', '15:40'),
    ('15:50', '16:35'),
    ('16:45', '17:30'),
    ('17:40', '18:25'),
    ('19:00', '19:45'),
    ('19:50', '20:35'),
  ];

  /// 按月份取当前适用的一套（5-9 月视为春夏季）
  static List<(String, String)> get current {
    final month = DateTime.now().month;
    return (month >= 5 && month <= 9) ? springSummer : autumnWinter;
  }

  static String startOf(int section) => current[section - 1].$1;
  static String endOf(int section) => current[section - 1].$2;
}
